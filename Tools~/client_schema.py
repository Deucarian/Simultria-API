"""Deterministic, example-free OpenAPI schemas and C# DTO emission."""
from __future__ import annotations

import hashlib
import json
import re
from xml.sax.saxutils import escape

from generate_contract import ContractError

HEADER = "// <auto-generated />\n// Regenerate with Tools~/update_contract.py; do not edit.\n"
NAMESPACE = "Deucarian.Simultria.API"
USINGS = """using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using Deucarian.API.Models;
using UnityEngine.Scripting;
"""


def literal(value):
    return json.dumps(value, ensure_ascii=True)


def identifier(value):
    parts = re.findall(r"[A-Za-z0-9]+", str(value))
    name = "".join(p[0].upper() + p[1:] for p in parts) or "Value"
    if name[0].isdigit():
        name = "Value" + name
    if len(name) > 100:
        name = name[:86] + hashlib.sha256(name.encode()).hexdigest()[:12]
    return name


def member_names(names, owner=""):
    result = {}
    used = {owner, "AdditionalProperties", "GetType", "ToString", "Equals", "GetHashCode"}
    for wire in sorted(names):
        name = identifier(wire)
        if name in used:
            name += hashlib.sha256(wire.encode()).hexdigest()[:8]
        used.add(name)
        result[wire] = name
    return result


def clean_schema(value, spec, stack=()):
    if not isinstance(value, dict):
        return {}
    if "$ref" in value:
        ref = value["$ref"]
        if not ref.startswith("#/"):
            raise ContractError("Only local OpenAPI references are supported.")
        if ref in stack:
            raise ContractError("Recursive OpenAPI schema needs an explicit named mapping: " + ref)
        target = spec
        try:
            for segment in ref[2:].split("/"):
                target = target[segment.replace("~1", "/").replace("~0", "~")]
        except (KeyError, TypeError) as error:
            raise ContractError("Unresolved OpenAPI reference: " + ref) from error
        return clean_schema(target, spec, stack + (ref,))
    result = {k: value[k] for k in ("type", "format", "nullable", "required") if k in value}
    for key in ("properties",):
        if key in value:
            result[key] = {str(k): clean_schema(v, spec, stack)
                           for k, v in sorted(value[key].items(), key=lambda pair: str(pair[0]))}
    for key in ("items", "additionalProperties"):
        if key in value:
            result[key] = clean_schema(value[key], spec, stack) if isinstance(value[key], dict) else value[key]
    for key in ("allOf", "oneOf", "anyOf"):
        if key in value:
            result[key] = [clean_schema(v, spec, stack) for v in value[key]]
    return result


class Models:
    def __init__(self):
        self.files = {}
        self.definitions = {}

    def type_name(self, schema, name, request=False, optional=False):
        schema = schema or {}
        if "allOf" in schema:
            merged = {"type": "object", "properties": {}, "required": []}
            for item in schema["allOf"]:
                if item.get("type", "object") != "object" or "properties" not in item:
                    return "JToken"
                merged["properties"].update(item["properties"])
                merged["required"].extend(item.get("required", []))
            schema = merged
        if "oneOf" in schema or "anyOf" in schema:
            return "JToken"
        kind = schema.get("type", "object" if "properties" in schema else "")
        if kind == "upload":
            return "SimultriaUpload"
        nullable = optional or schema.get("nullable", False)
        if kind in ("integer", "number", "boolean"):
            base = {"integer": "long" if schema.get("format") == "int64" else "int",
                    "number": "float" if schema.get("format") == "float" else "double",
                    "boolean": "bool"}[kind]
            return base + ("?" if nullable else "")
        if kind in ("string", "date", "datetime"):
            return "byte[]" if schema.get("format") in ("binary", "byte") else "string"
        if kind == "array":
            item = self.type_name(schema.get("items", {}), identifier(name + "Item"), request)
            return "List<" + item + ">"
        if kind == "object" and schema.get("properties"):
            name = identifier(name)
            key = json.dumps([schema, request], sort_keys=True)
            if name in self.definitions:
                if self.definitions[name] != key:
                    raise ContractError("Generated DTO name collision: " + name)
                return name
            self.definitions[name] = key
            self.emit(schema, name, request)
            return name
        if kind == "object" and isinstance(schema.get("additionalProperties"), dict):
            item = self.type_name(schema["additionalProperties"], identifier(name + "Value"), request)
            return "Dictionary<string, " + item + ">"
        return "JToken"

    def emit(self, schema, name, request):
        names = member_names(schema["properties"], name)
        properties = []
        fields = []
        methods = []
        for wire, prop in names.items():
            required = wire in schema.get("required", [])
            typ = self.type_name(schema["properties"][wire], identifier(name + prop), request,
                                 optional=not required)
            attributes = f"        [Preserve, JsonProperty({literal(wire)})]"
            if request:
                attributes = (f"        [Preserve, JsonProperty({literal(wire)}, "
                              "NullValueHandling = NullValueHandling.Include, "
                              "DefaultValueHandling = DefaultValueHandling.Include)]")
                field = "_" + prop[0].lower() + prop[1:]
                fields.extend([f"        private {typ} {field};", f"        private bool {field}Specified;"])
                properties.extend([attributes, f"        public {typ} {prop}", "        {",
                                   f"            get => {field};", "            set", "            {",
                                   f"                {field} = value;", f"                {field}Specified = true;",
                                   "            }", "        }"])
                methods.extend(["        [Preserve]", f"        public bool ShouldSerialize{prop}() => {field}Specified;"])
            else:
                properties.extend([attributes, f"        public {typ} {prop} {{ get; set; }}"])
        # Preserve undocumented response fields without fabricating their schema.
        if not request and schema.get("additionalProperties", True) is not False:
            properties.extend(["        [Preserve, JsonExtensionData]",
                               "        public IDictionary<string, JToken> AdditionalProperties { get; set; }"])
        sections = []
        for label, lines in (("Fields", fields), ("Properties", properties), ("Methods", methods)):
            if lines:
                sections += [f"        #region {label}", *lines, "        #endregion", ""]
        body = "\n".join(sections).rstrip()
        self.files[f"Models/{name}.g.cs"] = (HEADER + USINGS + f"\nnamespace {NAMESPACE}.Generated\n{{\n"
            + f"    [Serializable, Preserve]\n    public sealed class {name}\n    {{\n{body}\n    }}\n}}\n")
